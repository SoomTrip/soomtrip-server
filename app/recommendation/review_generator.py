import os
from openai import OpenAI
from dotenv import load_dotenv

load_dotenv()

client = OpenAI(api_key=os.getenv("AI_API_KEY"))

import random

def generate_one_line_review(
    region_name: str,
    
    theme_weights: dict,
    score_detail: dict,
) -> str:
    """
    추천된 여행지에 대한 감성적인 한줄평을 AI로 생성.

    - 여행지 스코어링 결과를 반영
    - 가장 높은 테마와 두 번째 테마를 활용
    - 크레파스로 그린 여행 그림 같은 분위기
    - 따뜻하고 아기자기하지만 유치하지 않은 표현
    - 지역명은 문구에 포함하지 않음
    """

    # --------------------------------------------------
    # 1. 테마 점수가 높은 순서대로 정렬
    # --------------------------------------------------

    sorted_themes = sorted(
        theme_weights.items(),
        key=lambda x: x[1],
        reverse=True
    )

    top_theme = (
        sorted_themes[0][0]
        if sorted_themes
        else "travel"
    )

    second_theme = (
        sorted_themes[1][0]
        if len(sorted_themes) > 1
        else None
    )


    # --------------------------------------------------
    # 2. 테마별 표현
    # --------------------------------------------------

    theme_hint_map = {

        "ocean": [
            "파도 소리",
            "잔잔한 물결",
            "시원한 바닷바람",
            "하얀 모래사장",
            "끝없이 펼쳐진 수평선",
            "살랑이는 파도",
            "작은 조개",
            "갈매기 소리",
            "반짝이는 바다",
            "해변의 여유",
            "바다 내음",
            "모래 위 발자국",
            "찰랑이는 파도",
            "따뜻한 해변",
        ],

        "nature": [
            "초록 숲",
            "살랑이는 나뭇잎",
            "맑은 새소리",
            "따뜻한 햇살",
            "시원한 산바람",
            "작은 꽃길",
            "푸른 들판",
            "나무 그늘",
            "숲속 오솔길",
            "싱그러운 풀잎",
        ],

        "activity": [
            "두근거리는 순간",
            "신나는 발걸음",
            "작은 모험",
            "짜릿한 하루",
            "새로운 발견",
            "즐거운 놀이",
            "활기찬 여행",
            "신나는 경험",
        ],

        "urban": [
            "알록달록한 골목",
            "반짝이는 거리",
            "작은 가게들",
            "따뜻한 카페",
            "도시의 불빛",
            "재미있는 골목길",
            "아기자기한 풍경",
            "오래된 간판",
        ],

        "healing": [
            "느긋한 오후",
            "포근한 햇살",
            "잔잔한 바람",
            "조용한 산책",
            "편안한 휴식",
            "따뜻한 하루",
            "느린 시간",
            "고요한 풍경",
        ],
    }


    # --------------------------------------------------
    # 3. 상위 테마에서 랜덤하게 표현 선택
    # --------------------------------------------------

    top_candidates = theme_hint_map.get(
        top_theme,
        ["여행의 설렘", "새로운 풍경"]
    )

    top_words = random.sample(
        top_candidates,
        min(4, len(top_candidates))
    )


    second_words = []

    if second_theme in theme_hint_map:

        second_candidates = theme_hint_map[second_theme]

        second_words = random.sample(
            second_candidates,
            min(2, len(second_candidates))
        )


    # --------------------------------------------------
    # 4. 문장 스타일 랜덤 선택
    # --------------------------------------------------

    styles = [
        "감성적인 여행 소개 문구",
        "따뜻한 그림책의 한 문장",
        "크레파스 그림 아래 적힌 짧은 문구",
        "여행 엽서에 적힌 한줄 문구",
        "아기자기한 여행 카드의 소개 문구",
        "짧은 동화 속 여행 장면",
    ]

    selected_style = random.choice(styles)


    # --------------------------------------------------
    # 5. AI 프롬프트
    # --------------------------------------------------

    prompt = f"""
여행지의 분위기를 소개하는 감성적인 한줄평을 작성해줘.

이 문구는 여행 앱의 여행지 카드에 들어가는
짧은 소개 문구야.

여행지 이름:
{region_name}

여행지 스코어:
{score_detail}

가장 높은 테마:
{top_theme}

가장 높은 테마의 관련 표현:
{", ".join(top_words)}

두 번째 테마:
{second_theme if second_theme else "없음"}

두 번째 테마의 관련 표현:
{", ".join(second_words) if second_words else "없음"}

이번 문장의 스타일:
{selected_style}


================================
원하는 분위기
================================

예시:

"파도 소리와 함께하는 완벽한 힐링"

처럼 감성적이고 깔끔한 여행지 소개 문구.

크레파스로 그린 여행 그림처럼
따뜻하고 아기자기한 분위기를 느낄 수 있게 작성해줘.

하지만 실제 어린아이의 말투처럼 쓰지는 마.

유치한 표현보다는
어린아이가 그린 그림을 바라보는 듯한
순수하고 따뜻한 분위기를 만들어줘.

문구를 읽었을 때
여행지의 모습이 머릿속에 간단한 그림처럼 떠올라야 해.


================================
스코어 반영
================================

가장 높은 테마를 문구의 중심으로 사용해.

두 번째 테마는 자연스럽게 어울릴 경우에만 사용해.

테마의 단어를 억지로 모두 넣지 말고,
가장 잘 어울리는 소재 1~2개만 사용해.

점수가 낮은 테마를 문구의 중심으로 만들지 마.


================================
표현 다양성
================================

같은 단어와 표현을 반복하지 마.

특히 다음 단어는 필요할 때만 사용하고
한 문구에서는 최대 한 번만 사용해:

푸른
설렘
작은
함께
하루
여행
바다

"푸른"이라는 단어를 매번 사용하지 마.

바다 테마라고 해서 항상
"푸른 바다", "푸른 물결"을 사용하지 마.

대신 다음과 같이 다양한 소재를 사용해:

파도 소리
바닷바람
모래사장
조개
갈매기
수평선
물결
해변
바다 내음
모래 위 발자국


================================
문장 구조
================================

한 가지 문장 구조를 반복하지 마.

다음 구조를 참고하되
매번 다른 구조를 선택해:

~와 함께하는 ~
~에서 만나는 ~
~이 선물하는 ~
~속에서 즐기는 ~
~을 따라 걷는 ~
~으로 물드는 ~
~이 머무는 ~
~이 가득한 ~
~을 닮은 ~


================================
금지 표현
================================

다음 표현은 절대 사용하지 마:

하고 싶어
가고 싶어
놀고 싶어
너무 좋아
하루
오전
오후

또한 지나치게 시적이거나
어려운 표현을 사용하지 마.


================================
문장 끝
================================

다음으로 끝내지 마:

~다
~합니다
~입니다
~해요
~어요
~네요
~요

문장 끝에는 마침표나 느낌표를 붙이지 마.


================================
지역명
================================

여행지 이름과 지역 이름은
절대로 문구에 포함하지 마.

여행지 이름은 오직 분위기와 특징을 파악하기 위한
참고 정보로만 사용해.


================================
최종 조건
================================

- 15~25자 내외
- 한 줄
- 감성적이고 깔끔하게
- 크레파스 그림 같은 따뜻함
- 아기자기하지만 유치하지 않게
- 여행지의 가장 높은 테마가 느껴지게
- 같은 표현 반복하지 않기
- 지역명 넣지 않기
- 마침표 사용하지 않기
- 느낌표 사용하지 않기
- 이모지 사용하지 않기
- 오전, 오후, 하루 등 특정 기간 또는 ~곳과 같이 장소를 암시하는 단어로 끝내지 않기
- ~요, ~다 등 종결어미로 끝내지 않기

위의 예시 문장을 그대로 복사하지 말고
새로운 문구를 만들어줘.

한줄평 하나만 출력해줘.
"""


    # --------------------------------------------------
    # 6. OpenAI 호출
    # --------------------------------------------------

    response = client.chat.completions.create(
        model="gpt-4o-mini",
        messages=[
            {
                "role": "user",
                "content": prompt
            }
        ],
        temperature=1.0,
        max_tokens=50,
    )


    # --------------------------------------------------
    # 7. 결과 정리
    # --------------------------------------------------

    review = response.choices[0].message.content.strip()

    # 혹시 붙어 있을 수 있는 문장부호 제거
    review = review.rstrip(".。!?！")

    return review